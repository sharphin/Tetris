package game.logic;

/**
 * スーパーローテーションシステム (SRS) の壁蹴りテーブル。
 * 回転後の位置がぶつかる場合、テーブルの順にずらして最初に置ける位置へ移動する。
 * オフセットは {x, y} で、y は上向きが正 (ガイドラインの表記どおり)。
 */
public final class SuperRotation {
    private SuperRotation() {}

    // [回転前の向き][0 = 右回転, 1 = 左回転][試行順]  向き: 0 = 出現時, 1 = R, 2 = 180°, 3 = L
    private static final int[][][][] JLSTZ = {
        { // 0 -> R, 0 -> L
            {{0, 0}, {-1, 0}, {-1, 1}, {0, -2}, {-1, -2}},
            {{0, 0}, {1, 0}, {1, 1}, {0, -2}, {1, -2}},
        },
        { // R -> 2, R -> 0
            {{0, 0}, {1, 0}, {1, -1}, {0, 2}, {1, 2}},
            {{0, 0}, {1, 0}, {1, -1}, {0, 2}, {1, 2}},
        },
        { // 2 -> L, 2 -> R
            {{0, 0}, {1, 0}, {1, 1}, {0, -2}, {1, -2}},
            {{0, 0}, {-1, 0}, {-1, 1}, {0, -2}, {-1, -2}},
        },
        { // L -> 0, L -> 2
            {{0, 0}, {-1, 0}, {-1, -1}, {0, 2}, {-1, 2}},
            {{0, 0}, {-1, 0}, {-1, -1}, {0, 2}, {-1, 2}},
        },
    };

    private static final int[][][][] I = {
        { // 0 -> R, 0 -> L
            {{0, 0}, {-2, 0}, {1, 0}, {-2, -1}, {1, 2}},
            {{0, 0}, {-1, 0}, {2, 0}, {-1, 2}, {2, -1}},
        },
        { // R -> 2, R -> 0
            {{0, 0}, {-1, 0}, {2, 0}, {-1, 2}, {2, -1}},
            {{0, 0}, {2, 0}, {-1, 0}, {2, 1}, {-1, -2}},
        },
        { // 2 -> L, 2 -> R
            {{0, 0}, {2, 0}, {-1, 0}, {2, 1}, {-1, -2}},
            {{0, 0}, {1, 0}, {-2, 0}, {1, -2}, {-2, 1}},
        },
        { // L -> 0, L -> 2
            {{0, 0}, {1, 0}, {-2, 0}, {1, -2}, {-2, 1}},
            {{0, 0}, {-2, 0}, {1, 0}, {-2, -1}, {1, 2}},
        },
    };

    private static final int[][] NONE = {{0, 0}};

    /**
     * @param type      ミノの種類 (Mino.Z など)
     * @param from      回転前の向き (0〜3)
     * @param clockwise 右回転なら true
     */
    public static int[][] kicks(int type, int from, boolean clockwise) {
        int dir = clockwise ? 0 : 1;
        if (type == Mino.O) return NONE;
        if (type == Mino.I) return I[from][dir];
        return JLSTZ[from][dir];
    }
}
